import { expect, test } from '../fixtures'

import { answerQuestions, confirmFacts } from '../helpers'

test('home page reads API health in Hindi and English', async ({ page }) => {
  await page.goto('/')
  const status = page.getByTestId('health-status')
  await expect(status).toHaveAttribute('data-state', 'ok')
  await expect(status).toContainText('सर्वर से जुड़ाव है')
  await page.getByRole('button', { name: 'English' }).click()
  await expect(status).toContainText('Server is reachable')
})

test('typed cough visit in Hindi reaches MEDIUM with the demonstration banner', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('start-visit').click()
  await page.getByLabel('नाम').fill('परीक्षण व्यक्ति (काल्पनिक)')
  await page.getByLabel('उम्र (साल)').fill('45')
  await page.getByRole('button', { name: 'पुरुष' }).click()
  await page.getByTestId('person-start').click()
  await page.getByTestId('capture-text').fill('काल्पनिक: तीन हफ़्ते से खांसी')
  await page.getByTestId('capture-continue').click()
  await answerQuestions(page, { cough_present: 'yes', cough_duration_days: 21 })
  await confirmFacts(page)
  const band = page.getByTestId('urgency-band')
  await expect(band).toHaveAttribute('data-level', 'MEDIUM')
  await expect(band).toContainText('जल्द डॉक्टर को दिखाएँ')
  await expect(page.getByTestId('draft-banner')).toBeVisible()
  await page.getByText('क्यों?').click()
  await expect(page.getByTestId('why')).toContainText('cough for 2 weeks or more')
  await page.getByTestId('to-plan').click()
  await expect(page.getByTestId('plan')).toContainText('प्राथमिक स्वास्थ्य केंद्र')
  await expect(page.getByTestId('draft-banner')).toBeVisible()
})

