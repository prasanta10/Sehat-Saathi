test('logging in and out; the danger-sign check works on the login screen', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('e2e-logged-out', '1'))
  await page.addInitScript(() => localStorage.removeItem('sehat.auth'))
  await page.goto('/')
  await expect(page.getByTestId('login-submit')).toBeVisible()
  await page.getByTestId('danger-button').click()
  await page.getByTestId('sign-general.profuse_bleeding').click()
  await expect(page.getByTestId('emergency-screen')).toBeVisible()
  await page.goto('/login')
  await page.getByLabel('मोबाइल नंबर (10 अंक)').fill('9000000001')
  await page.getByLabel('पिन').fill('0000')
  await page.getByTestId('login-submit').click()
  await expect(page.getByRole('alert')).toContainText('पिन ग़लत')
  await page.getByLabel('पिन').fill('1234')
  await page.getByTestId('login-submit').click()
  await expect(page.getByTestId('start-visit')).toBeVisible()
  await page.getByTestId('logout').click()
  await expect(page.getByTestId('login-submit')).toBeVisible()
})
