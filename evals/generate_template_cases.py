"""Generate template-based synthetic eval cases (evals/cases/text/template.yaml).

Deterministic (fixed seed). These broaden coverage of phrasing combinations; they are not a
substitute for hand-authored, Hindi-speaker-reviewed cases.
"""

import random
from pathlib import Path

DURATIONS = [
    ("teen hafte", 21),
    ("do hafte", 14),
    ("das din", 10),
    ("ek mahina", 30),
    ("5 din", 5),
    ("ek hafte", 7),
    ("13 din", 13),
    ("14 din", 14),
    ("तीन हफ़्ते", 21),
    ("दो हफ़्ते", 14),
    ("दस दिन", 10),
    ("चार दिन", 4),
]
COUGH = ["{d} se khansi hai", "khansi {d} se hai", "{d} से खांसी है"]
FEVER = [
    ("bukhar nahi hai", {"fever_present": "no"}),
    ("बुखार नहीं है", {"fever_present": "no"}),
    ("bukhar {d} se hai", "fever_dur"),
    ("", {}),
]
EXTRAS = [
    ("balgam mein khoon aata hai", {"blood_in_sputum": "yes"}),
    ("balgam mein khoon nahi aata", {"blood_in_sputum": "no"}),
    ("raat ko pasina aata hai", {"night_sweats": "yes"}),
    ("रात को पसीना आता है", {"night_sweats": "yes"}),
    ("wajan kam ho gaya hai", {"significant_weight_loss": "yes"}),
    ("ghar mein maa ko TB hai", {"tb_household_contact": "yes"}),
    ("aaj mausam theek hai", {}),
    ("bus ka kiraya bahut hai", {}),
]


def main() -> None:
    rng = random.Random(20261111)
    lines = [
        "# GENERATED by evals/generate_template_cases.py — do not edit by hand. Synthetic.",
        "pathway: adult_cough",
        "cases:",
    ]
    for i in range(45):
        d, days = rng.choice(DURATIONS)
        parts = [rng.choice(COUGH).format(d=d)]
        gold: dict[str, object] = {"cough_present": "yes", "cough_duration_days": days}
        ftext, fgold = rng.choice(FEVER)
        if fgold == "fever_dur":
            fd, fdays = rng.choice(DURATIONS[:8])
            parts.append(ftext.format(d=fd))
            gold.update({"fever_present": "yes", "fever_duration_days": fdays})
        elif ftext:
            parts.append(ftext)
            gold.update(fgold)
        for etext, egold in rng.sample(EXTRAS, rng.randint(0, 2)):
            parts.append(etext)
            gold.update(egold)
        rng.shuffle(parts)
        text = ". ".join(p[0].upper() + p[1:] for p in parts) + "."
        g = ", ".join(f"{k}: {v!r}".replace("'", '"') for k, v in gold.items())
        lines += [f"  - id: t{i + 1:02d}", f'    text: "{text}"', f"    gold: {{{g}}}"]
    Path(__file__).with_name("cases").joinpath("text", "template.yaml").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
